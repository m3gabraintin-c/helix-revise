AOS_RE = re.compile(r"^Unit (\d) AOS (\d+): (.+)$")
UNIT_RE = re.compile(r"^Unit (\d): (.+)$")

def written_rubric(answer, marks):
    """Split a model answer into marking points that add up to the question's exam marks (flagged for review)."""
    if marks == 0: return [("Assessed as part of the whole conversation: " + answer, 0)]
    bits = [b.strip() for b in re.split(r"(?<=[.;!?])\s+|\s+(?=\([a-z]\)\s)", answer) if b.strip()]
    if len(bits) >= marks:  # group consecutive points into `marks` criteria of 1 mark each
        size, extra, out, k = len(bits) // marks, len(bits) % marks, [], 0
        for g in range(marks):
            n = size + (1 if g < extra else 0); out.append((" ".join(bits[k:k + n]), 1)); k += n
        return out
    return [(b, 1) for b in bits[:-1]] + [(bits[-1], marks - len(bits) + 1)] if bits else [(answer, marks)]

def sync(con, d):
    """Make the database match DATA. Fields DATA does not carry (provenance, study design details, areas of study,
    rubrics of MCQ and written questions, extra secondary tags, revisions) are kept."""
    cur = con.cursor()
    stamp = now()
    def sigs(data):  # what the site shows of each question, so unchanged questions are left exactly as they are
        out = {}
        for slug, rows in data["Q"].items():
            for k, r in enumerate(rows): out[r["id"] if isinstance(r, dict) else r[0]] = ["Q", slug, k, r]
        for sid, rows in data.get("X", {}).items():
            for k, r in enumerate(rows): out[r["id"]] = ["X", sid, k, r]
        ch = set(data.get("C", []))
        return {i: json.dumps(v + [data["T"].get(i), i in ch], ensure_ascii=False, sort_keys=True) for i, v in out.items()}
    before = sigs(export_data(con)) if cur.execute("SELECT count(*) FROM question").fetchone()[0] else {}
    after = sigs(d)
    for i, (code, name, desc) in enumerate(QTYPES):
        cur.execute("INSERT INTO question_type VALUES(?,?,?,?) ON CONFLICT(code) DO UPDATE SET name=excluded.name, description=excluded.description, position=excluded.position", (code, name, desc, i))
    slug_ids = {}
    for pos, (sid, name, label, grp, T) in enumerate(d["S"]):
        m = re.search(r"Units (\d) & (\d)", label)
        u = (int(m.group(1)), int(m.group(2))) if m else (None, None)
        cur.execute("""INSERT INTO subject VALUES(?,?,?,?,?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET name=excluded.name, label=excluded.label,
                       grp=excluded.grp, position=excluded.position""",
                    (sid, name, label, grp, "GCSE" if label.startswith("GCSE") else "VCE", u[0], u[1], DISCIPLINE.get(sid, sid), 1000 + pos))
        for code in allowed_types(sid): cur.execute("INSERT OR IGNORE INTO subject_question_type VALUES(?,?)", (sid, code))
        row = cur.execute("SELECT id FROM study_design WHERE subject_id=? AND status='current'", (sid,)).fetchone()
        if row: did = row[0]
        else:
            cur.execute("INSERT INTO study_design(subject_id, version, title, status, notes) VALUES(?,?,?,?,?)",
                        (sid, "current", ("Edexcel GCSE (9-1) Biology specification" if label.startswith("GCSE") else f"VCE {name} study design"),
                         "current", "Imported from the site. Confirm the version and accreditation years, and map each topic to its area of study."))
            did = cur.lastrowid
        for num, tname, subs in T:
            trow = cur.execute("SELECT id FROM topic WHERE study_design_id=? AND number=?", (did, num)).fetchone()
            if trow:
                tid = trow[0]; cur.execute("UPDATE topic SET name=? WHERE id=?", (tname, tid))
            else:
                aos = None
                if not all(s[0].endswith("-challenge") for s in subs):  # the Challenge questions topic has no area of study
                    am, um = AOS_RE.match(tname), UNIT_RE.match(tname)
                    code, unit, aname = (f"Unit {am.group(1)} AOS {am.group(2)}", int(am.group(1)), am.group(3)) if am else \
                                        (None, int(um.group(1)), um.group(2)) if um else (None, None, tname)
                    found = cur.execute("SELECT id FROM area_of_study WHERE study_design_id=? AND code IS ? AND (code IS NOT NULL OR name=?)",
                                        (did, code, aname)).fetchone() if code else None
                    if found: aos = found[0]
                    else:
                        npos = cur.execute("SELECT ifnull(max(position),0)+1 FROM area_of_study WHERE study_design_id=?", (did,)).fetchone()[0]
                        cur.execute("INSERT INTO area_of_study(study_design_id, unit, code, name, position) VALUES(?,?,?,?,?)", (did, unit, code, aname, npos))
                        aos = cur.lastrowid
                cur.execute("INSERT INTO topic(study_design_id, area_of_study_id, number, name) VALUES(?,?,?,?)", (did, aos, num, tname)); tid = cur.lastrowid
            for p, (slug, sname, triple) in enumerate(subs):
                meta = d.get("M", {}).get(slug)
                kind = "collection" if slug.endswith("-challenge") else "syllabus"
                vals = (tid, -1 - p, sname, kind, int(bool(triple)), meta[0] if meta else None, meta[2] if meta else "", meta[3] if meta and len(meta) > 3 else None)
                srow = cur.execute("SELECT id FROM subtopic WHERE slug=?", (slug,)).fetchone()
                if srow: cur.execute("UPDATE subtopic SET topic_id=?, position=?, name=?, kind=?, triple_only=?, exam_weight=?, prior_knowledge=?, format_note=? WHERE id=?", vals + (srow[0],)); slug_ids[slug] = srow[0]
                else: cur.execute("INSERT INTO subtopic(topic_id, position, name, kind, triple_only, exam_weight, prior_knowledge, format_note, slug) VALUES(?,?,?,?,?,?,?,?,?)", vals + (slug,)); slug_ids[slug] = cur.lastrowid
        cur.execute("UPDATE subtopic SET position = -position - 1 WHERE position < 0")  # two steps, so positions never collide
        e = d.get("E", {}).get(sid)
        if e: cur.execute("INSERT OR REPLACE INTO relevance_wording VALUES(?,?,?,?,?,?,?,?)", (sid, *e["w"], e["mcq"], e["short"], e["multi"], e.get("free")))
    # prerequisites (current designs)
    cur.execute("DELETE FROM subtopic_prerequisite WHERE subtopic_id IN (SELECT id FROM subtopic WHERE slug IN (%s))" % ",".join("?" * len(slug_ids)), list(slug_ids))
    for slug, meta in d.get("M", {}).items():
        for k, pre in enumerate(meta[1]): cur.execute("INSERT INTO subtopic_prerequisite VALUES(?,?,?)", (slug_ids[slug], slug_ids[pre], k))

    # questions
    design_of = {sid: cur.execute("SELECT id FROM study_design WHERE subject_id=? AND status='current'", (sid,)).fetchone()[0] for sid, *_ in d["S"]}
    subj_of = {slug: s[0] for s in d["S"] for _, _, subs in s[4] for slug, _, _ in subs}
    chal, T = set(d.get("C", [])), d.get("T", {})
    seen = []
    def upsert(r, sid, home, hpos, xpos):
        qid = r["id"] if isinstance(r, dict) else r[0]; seen.append(qid)
        if before.get(qid) == after[qid]: return
        t = T[qid]
        if isinstance(r, dict):
            fmt, prompt, answer, expl, higher, tech, steps_label = "multi", r["title"], None, None, 0, r.get("tech"), r.get("steps_label")
        elif r[1] == 0: fmt, prompt, answer, expl, higher, tech, steps_label = "mcq", r[2], None, r[5], r[6], None, None
        else: fmt, prompt, answer, expl, higher, tech, steps_label = "written", r[2], r[3], r[4], r[5], None, None
        area = t[3] if len(t) > 3 and t[3] not in subj_of else None
        source = r.get("source") if isinstance(r, dict) else None
        old = cur.execute("SELECT exam_marks FROM question WHERE id=?", (qid,)).fetchone()
        cols = dict(subject_id=sid, format=fmt, home_subtopic_id=slug_ids[home] if home else None, home_position=hpos, exam_position=xpos,
                    prompt=prompt, answer=answer, explanation=expl, higher_only=int(bool(higher)), tech=tech, steps_label=steps_label,
                    is_challenge=int(qid in chal), exam_marks=t[1], minutes=float(t[2]), area_label=area, source=source)
        if old:
            cur.execute("UPDATE question SET %s, updated_at=? WHERE id=?" % ", ".join(f"{k}=?" for k in cols), (*cols.values(), stamp, qid))
        else:
            cur.execute("INSERT INTO question(id, %s, provenance_note, created_at, updated_at) VALUES(?, %s, ?, ?, ?)" % (", ".join(cols), ", ".join("?" * len(cols))),
                        (qid, *cols.values(), "Imported from index.html (written for this site; some questions were drafted with AI help and then reviewed).", stamp, stamp))
        # types
        cur.execute("DELETE FROM question_question_type WHERE question_id=?", (qid,))
        for k, code in enumerate(t[0] if isinstance(t[0], list) else [t[0]]): cur.execute("INSERT INTO question_question_type VALUES(?,?,?)", (qid, code, k))
        # topics: primary from the home subtopic (or the subtopic a Challenge-set question tests), secondary from the parts
        did = design_of[sid]
        if home and not home.endswith("-challenge"): primary = home
        elif home: primary = t[3] if len(t) > 3 and t[3] in subj_of else None
        else:
            by = {}
            for p in r["pieces"]:
                if p["kind"] == "part": by[p["topic"]] = by.get(p["topic"], 0) + p["marks"]
            primary = max(by, key=lambda s: (by[s], -list(by).index(s)))
        derived = {primary} if primary else set()
        if isinstance(r, dict): derived |= {p["topic"] for p in r["pieces"] if p["kind"] == "part"}
        cur.execute("DELETE FROM question_topic WHERE question_id=? AND study_design_id=? AND (role='primary' OR subtopic_id IN (%s))" % ",".join(["?"] * len(derived) or ["NULL"]),
                    (qid, did, *[slug_ids[s] for s in derived]))
        for s in sorted(derived, key=lambda s: s != primary):
            cur.execute("INSERT INTO question_topic VALUES(?,?,?,?)", (qid, slug_ids[s], did, "primary" if s == primary else "secondary"))
        # content and rubric
        if fmt == "mcq":
            cur.execute("DELETE FROM mcq_option WHERE question_id=?", (qid,))
            for k, o in enumerate(r[3]): cur.execute("INSERT INTO mcq_option VALUES(?,?,?,?)", (qid, k, o, int(k == r[4])))
            cur.execute("DELETE FROM rubric_criterion WHERE question_id=?", (qid,))
            cur.execute("INSERT INTO rubric_criterion(question_id, position, description, marks) VALUES(?,?,?,?)",
                        (qid, 0, f"Chooses {'ABCDEFGH'[r[4]]}: {r[3][r[4]]}", 1))
        elif fmt == "written":
            have = cur.execute("SELECT ifnull(sum(marks),-1), count(*) FROM rubric_criterion WHERE question_id=?", (qid,)).fetchone()
            if have[1] == 0 or (old and old[0] != t[1] and have[0] != t[1]):  # new, or the marks changed: regenerate
                cur.execute("DELETE FROM rubric_criterion WHERE question_id=?", (qid,))
                for k, (desc, mk) in enumerate(written_rubric(answer, t[1])):
                    cur.execute("INSERT INTO rubric_criterion(question_id, position, description, marks, needs_review) VALUES(?,?,?,?,1)", (qid, k, desc, mk))
        else:
            cur.execute("DELETE FROM question_piece WHERE question_id=?", (qid,))  # cascades to the parts' rubric criteria
            cur.execute("DELETE FROM rubric_criterion WHERE question_id=?", (qid,))
            for k, p in enumerate(r["pieces"]):
                if p["kind"] == "info":
                    dg = p.get("diagram")
                    cur.execute("INSERT INTO question_piece(question_id, position, kind, text, table_json, diagram_svg, diagram_alt) VALUES(?,?,?,?,?,?,?)",
                                (qid, k, "info", p.get("text"), json.dumps(p["table"], ensure_ascii=False) if "table" in p else None,
                                 dg["svg"] if dg else None, dg["alt"] if dg else None))
                else:
                    cur.execute("""INSERT INTO question_piece(question_id, position, kind, label, part_question, marks, answer, mistake, subtopic_id, sample_json)
                                   VALUES(?,?,?,?,?,?,?,?,?,?)""", (qid, k, "part", p["label"], p["question"], p["marks"], p["answer"], p["mistake"],
                                   slug_ids[p["topic"]], json.dumps(p["sample"], ensure_ascii=False) if "sample" in p else None))
                    pid = cur.lastrowid
                    for j, st in enumerate(p["steps"]):
                        cur.execute("INSERT INTO rubric_criterion(question_id, piece_id, position, description, marks) VALUES(?,?,?,?,?)", (qid, pid, j, st["working"], st["marks"]))
    for slug, rows in d["Q"].items():
        for k, r in enumerate(rows): upsert(r, subj_of[slug], slug, k, None)
    for sid, rows in d.get("X", {}).items():
        for k, r in enumerate(rows): upsert(r, sid, None, None, k)
    gone = [x[0] for x in cur.execute("SELECT id FROM question") if x[0] not in set(seen)]
    for qid in gone: cur.execute("DELETE FROM question WHERE id=?", (qid,))
    con.commit()
    return len(seen), len(gone)

