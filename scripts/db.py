def allowed_types(sid):
    base = {"recall", "concept", "apply", "data", "eval"}
    if sid in MATHS: return base | {"calc", "proof"}
    if sid == "vce-english34": return base | {"text", "write"}
    if sid == "vce-chinese-sl34": return base | {"read", "write", "lang", "speak"}
    return base | {"calc", "design"}  # sciences, psychology and GCSE Biology

now = lambda: datetime.datetime.now().replace(microsecond=0).isoformat()

def connect(path=DBFILE):
    con = sqlite3.connect(path)
    con.execute("PRAGMA foreign_keys = ON")
    return con

def read_html():
    lines = open(HTML, encoding="utf-8").read().split("\n")
    i = next(k for k, l in enumerate(lines) if l.startswith(PREFIX))
    return lines, i, json.loads(lines[i][len(PREFIX):].rstrip().rstrip(";"))

# ---------- dump and build ----------

def sql_value(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return str(int(v))
    if isinstance(v, int): return str(v)
    if isinstance(v, float): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def dump(con, path=DATA_SQL):
    out = ["-- Rows of the Helix Revise question database, one per line. Generated by scripts/db.py dump; edit through the",
           "-- admin page (python admin/server.py) or index.html + python scripts/db.py sync, not by hand.", "BEGIN;"]
    for t, order in TABLES:
        for row in con.execute(f"SELECT * FROM {t} ORDER BY {order}"):
            out.append(f"INSERT INTO {t} VALUES({','.join(sql_value(v) for v in row)});")
    out.append("COMMIT;")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")

def build(path=DBFILE):
    if os.path.exists(path): os.remove(path)
    con = connect(path)
    con.executescript(open(SCHEMA, encoding="utf-8").read())
    if os.path.exists(DATA_SQL): con.executescript(open(DATA_SQL, encoding="utf-8").read())
    con.commit()
    return con

def open_db():
    return connect() if os.path.exists(DBFILE) else build()

