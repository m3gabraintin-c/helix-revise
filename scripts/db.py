def export_data(con):
    q1 = lambda sql, *a: con.execute(sql, a).fetchall()
    S, Q, X, C, M, T, E = [], {}, {}, [], {}, {}, {}
    pieces_of, steps_of, options_of, types_of = {}, {}, {}, {}
    for qid, code in q1("SELECT question_id, type_code FROM question_question_type ORDER BY question_id, position"): types_of.setdefault(qid, []).append(code)
    for qid, text, ok in q1("SELECT question_id, text, is_correct FROM mcq_option ORDER BY question_id, position"): options_of.setdefault(qid, []).append((text, ok))
    for pid, desc, mk in q1("SELECT piece_id, description, marks FROM rubric_criterion WHERE piece_id IS NOT NULL ORDER BY piece_id, position"):
        steps_of.setdefault(pid, []).append({"working": desc, "marks": mk})
    slug_by_id = dict(q1("SELECT id, slug FROM subtopic"))
    for row in q1("SELECT id, question_id, kind, text, table_json, diagram_svg, diagram_alt, label, part_question, marks, answer, mistake, subtopic_id, sample_json FROM question_piece ORDER BY question_id, position"):
        pid, qid, kind, text, tj, svg, alt, label, pq, mk, ans, mis, sub, sj = row
        if kind == "info":
            p = {"kind": "info"}
            if text is not None: p["text"] = text
            if tj is not None: p["table"] = json.loads(tj)
            if svg is not None: p["diagram"] = {"svg": svg, "alt": alt}
        else:
            p = {"kind": "part", "label": label, "question": pq, "marks": mk, "answer": ans, "steps": steps_of.get(pid, []), "mistake": mis, "topic": slug_by_id[sub]}
            if sj is not None: p["sample"] = json.loads(sj)
        pieces_of.setdefault(qid, []).append(p)
    primary = dict(q1("""SELECT x.question_id, s.slug FROM question_topic x JOIN subtopic s ON s.id = x.subtopic_id JOIN study_design d ON d.id = x.study_design_id
                         WHERE x.role = 'primary' AND d.status = 'current'"""))
    def row_of(q):
        qid, fmt, prompt, answer, expl, higher, tech, steps_label, source = q
        if fmt == "multi":
            r = {"id": qid, "type": "multi", "title": prompt, "source": source}
            if steps_label: r["steps_label"] = steps_label
            if tech: r["tech"] = tech
            r["pieces"] = pieces_of.get(qid, [])
            return r
        if fmt == "mcq":
            opts = options_of[qid]
            return [qid, 0, prompt, [o for o, _ in opts], next(k for k, (_, ok) in enumerate(opts) if ok), expl, higher]
        return [qid, 1, prompt, answer, expl, higher]
    QCOLS = "q.id, q.format, q.prompt, q.answer, q.explanation, q.higher_only, q.tech, q.steps_label, q.source"
    for sid, name, label, grp in q1("SELECT id, name, label, grp FROM subject ORDER BY position"):
        did = q1("SELECT id FROM study_design WHERE subject_id=? AND status='current'", sid)[0][0]
        topics = []
        for tid, num, tname in q1("SELECT id, number, name FROM topic WHERE study_design_id=? ORDER BY number", did):
            subs = []
            for stid, slug, sname, kind, triple, w, prior, note in q1("SELECT id, slug, name, kind, triple_only, exam_weight, prior_knowledge, format_note FROM subtopic WHERE topic_id=? ORDER BY position", tid):
                subs.append([slug, sname, triple])
                if w is not None:
                    M[slug] = [w, [x[0] for x in q1("SELECT s.slug FROM subtopic_prerequisite p JOIN subtopic s ON s.id = p.prerequisite_id WHERE p.subtopic_id=? ORDER BY p.position", stid)], prior] + ([note] if note else [])
                rows = q1(f"SELECT {QCOLS} FROM question q WHERE q.home_subtopic_id=? ORDER BY q.home_position", stid)
                if rows: Q[slug] = [row_of(q) for q in rows]
            topics.append([num, tname, subs])
        S.append([sid, name, label, grp, topics])
        xs = q1(f"SELECT {QCOLS} FROM question q WHERE q.subject_id=? AND q.exam_position IS NOT NULL ORDER BY q.exam_position", sid)
        if xs: X[sid] = [row_of(q) for q in xs]
        w = q1("SELECT w_low, w_medium, w_high, mcq, short, multi, free FROM relevance_wording WHERE subject_id=?", sid)
        if w:
            E[sid] = {"w": list(w[0][:3]), "mcq": w[0][3], "short": w[0][4], "multi": w[0][5]}
            if w[0][6]: E[sid]["free"] = w[0][6]
    for qid, marks, minutes, area, chal, kind in q1("""SELECT q.id, q.exam_marks, q.minutes, q.area_label, q.is_challenge, s.kind FROM question q
                                                       LEFT JOIN subtopic s ON s.id = q.home_subtopic_id ORDER BY q.id"""):
        ty = types_of.get(qid, [])
        T[qid] = [ty[0] if len(ty) == 1 else ty, marks, minutes]
        if kind == "collection": T[qid].append(primary.get(qid) or area)
        if chal: C.append(qid)
    return {"S": S, "Q": Q, "X": X, "C": C, "M": M, "T": T, "E": E}

def write_html(data):
    lines, i, _ = read_html()
    out = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    assert "</script" not in out.lower() and "<!--" not in out
    lines[i] = PREFIX + out + ";"  # any line after it (such as const DIFF) is left alone
    open(HTML, "w", encoding="utf-8", newline="").write("\n".join(lines))

def same(a, b):
    """DATA equality, ignoring dictionary key order and the order of DATA.C (a set of ids)."""
    a, b = dict(a), dict(b)
    return set(a.pop("C", [])) == set(b.pop("C", [])) and a == b

