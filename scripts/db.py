def validate(con, qids=None):
    """Return a list of problems. qids limits the per-question checks (the admin page validates the question it saved)."""
    errs, q = [], lambda sql, *a: con.execute(sql, a).fetchall()
    only = "" if qids is None else " AND q.id IN (%s)" % ",".join("'%s'" % x.replace("'", "''") for x in qids)
    if qids is None:
        for (sid,) in q("SELECT id FROM subject s WHERE NOT EXISTS (SELECT 1 FROM study_design d WHERE d.subject_id = s.id AND d.status = 'current')"):
            errs.append(f"subject {sid}: no current study design")
        for (sid,) in q("SELECT id FROM subject s WHERE NOT EXISTS (SELECT 1 FROM relevance_wording w WHERE w.subject_id = s.id)"):
            errs.append(f"subject {sid}: no exam-relevance wording")
        for (sid,) in q("SELECT subject_id FROM relevance_wording WHERE free IS NOT NULL AND subject_id NOT IN (%s)" % ",".join(f"'{m}'" for m in MATHS)):
            errs.append(f"subject {sid}: only maths courses have technology-free wording")
        # areas of study: a subtopic's own area, or else its topic's (view subtopic_area)
        for slug, u, a, b in q("""SELECT s.slug, a.unit, sj.unit_from, sj.unit_to FROM subtopic s JOIN subtopic_area sa ON sa.subtopic_id = s.id
                                  JOIN area_of_study a ON a.id = sa.area_of_study_id JOIN topic t ON t.id = s.topic_id
                                  JOIN study_design d ON d.id = t.study_design_id JOIN subject sj ON sj.id = d.subject_id
                                  WHERE a.unit IS NOT NULL AND (sj.unit_from IS NULL OR a.unit NOT BETWEEN sj.unit_from AND sj.unit_to)"""):
            errs.append(f"subtopic {slug}: its area of study is in Unit {u}, outside the subject's units")
        for (name,) in q("""SELECT s.slug FROM subtopic s JOIN subtopic_area sa ON sa.subtopic_id = s.id JOIN area_of_study a ON a.id = sa.area_of_study_id
                            JOIN topic t ON t.id = s.topic_id WHERE a.study_design_id <> t.study_design_id"""):
            errs.append(f"subtopic {name}: area of study from another study design")
        for (slug,) in q("""SELECT s.slug FROM subtopic s JOIN subtopic_area sa ON sa.subtopic_id = s.id JOIN topic t ON t.id = s.topic_id
                            JOIN study_design d ON d.id = t.study_design_id WHERE s.kind = 'syllabus' AND d.status = 'current' AND sa.area_of_study_id IS NULL"""):
            errs.append(f"subtopic {slug}: no area of study")
        for (slug,) in q("""SELECT s.slug FROM subtopic s JOIN topic t ON t.id = s.topic_id JOIN study_design d ON d.id = t.study_design_id
                            WHERE s.kind = 'syllabus' AND d.status <> 'retired' AND s.exam_weight IS NULL"""):
            errs.append(f"subtopic {slug}: no exam-relevance weight")
        for a, b in q("""SELECT s.slug, p.slug FROM subtopic_prerequisite x JOIN subtopic s ON s.id = x.subtopic_id JOIN subtopic p ON p.id = x.prerequisite_id
                         JOIN topic tp ON tp.id = p.topic_id JOIN study_design dp ON dp.id = tp.study_design_id
                         JOIN topic ts ON ts.id = s.topic_id JOIN study_design ds ON ds.id = ts.study_design_id
                         JOIN subject sp ON sp.id = dp.subject_id JOIN subject sb ON sb.id = ds.subject_id
                         WHERE p.kind <> 'syllabus' OR dp.status = 'retired' OR sp.curriculum <> sb.curriculum OR ifnull(sp.unit_from, 0) > ifnull(sb.unit_to, 9)"""):
            errs.append(f"subtopic {a}: prerequisite {b} is retired, a collection, from another curriculum or from a later unit")
        # prerequisite cycles
        graph = {}
        for a, b in q("SELECT subtopic_id, prerequisite_id FROM subtopic_prerequisite"): graph.setdefault(a, []).append(b)
        state = {}
        def visit(n, path):
            state[n] = 1
            for m in graph.get(n, []):
                if state.get(m) == 1: errs.append("prerequisite cycle through subtopic ids " + " -> ".join(map(str, path + [m]))); continue
                if not state.get(m): visit(m, path + [m])
            state[n] = 2
        for n in list(graph):
            if not state.get(n): visit(n, [n])
    # per question
    for (qid,) in q(f"""SELECT q.id FROM question q JOIN subtopic s ON s.id = q.home_subtopic_id JOIN topic t ON t.id = s.topic_id
                        JOIN study_design d ON d.id = t.study_design_id WHERE d.subject_id <> q.subject_id{only}"""):
        errs.append(f"question {qid}: listed under a subtopic of another subject")
    rows = q(f"""SELECT q.id, q.subject_id, q.format, q.home_subtopic_id, s.kind, q.exam_marks, q.area_label, q.tech, q.higher_only, sj.curriculum,
                        (SELECT x.subtopic_id FROM question_topic x JOIN study_design d ON d.id = x.study_design_id WHERE x.question_id = q.id AND x.role = 'primary' AND d.status = 'current')
                 FROM question q JOIN subject sj ON sj.id = q.subject_id LEFT JOIN subtopic s ON s.id = q.home_subtopic_id WHERE 1=1{only}""")
    types = {}
    for qid, code in q(f"SELECT question_id, type_code FROM question_question_type x JOIN question q ON q.id = x.question_id WHERE 1=1{only}"): types.setdefault(qid, []).append(code)
    allowed = {}
    for sid, code in q("SELECT subject_id, type_code FROM subject_question_type"): allowed.setdefault(sid, set()).add(code)
    rubric = {}
    for qid, pid, mk in q(f"SELECT question_id, piece_id, marks FROM rubric_criterion r JOIN question q ON q.id = r.question_id WHERE 1=1{only}"):
        rubric.setdefault((qid, pid), 0); rubric[(qid, pid)] += mk
    parts = {}
    for qid, pid, mk, sub, ssid in q(f"""SELECT p.question_id, p.id, p.marks, p.subtopic_id, d.subject_id FROM question_piece p JOIN question q ON q.id = p.question_id
                                       JOIN subtopic s ON s.id = p.subtopic_id JOIN topic t ON t.id = s.topic_id JOIN study_design d ON d.id = t.study_design_id
                                       WHERE p.kind = 'part'{only}"""):
        parts.setdefault(qid, []).append((pid, mk, sub, ssid))
    tags = {}
    for qid, sub in q(f"SELECT question_id, subtopic_id FROM question_topic x JOIN question q ON q.id = x.question_id WHERE 1=1{only}"): tags.setdefault(qid, set()).add(sub)
    opts = {}
    for qid, ok in q(f"SELECT question_id, is_correct FROM mcq_option o JOIN question q ON q.id = o.question_id WHERE 1=1{only}"): opts.setdefault(qid, []).append(ok)
    for qid, sid, fmt, home, hkind, marks, area, tech, higher, curric, prim in rows:
        w = f"question {qid}:"
        ty = types.get(qid, [])
        if not ty: errs.append(f"{w} no question type")
        for code in ty:
            if code not in allowed.get(sid, ()): errs.append(f"{w} type {code} is not allowed for {sid}")
        if hkind == "collection":
            if (prim is None) == (area is None): errs.append(f"{w} a Challenge-set question needs a primary subtopic or an area label, not both")
        else:
            if area is not None: errs.append(f"{w} only Challenge-set questions have an area label")
            if prim is None: errs.append(f"{w} no primary subtopic in the current study design")
            elif home is not None and prim != home: errs.append(f"{w} its primary subtopic must be the subtopic it is listed under")
        if tech and sid not in MATHS: errs.append(f"{w} technology-free/active applies to maths courses only")
        if higher and curric != "GCSE": errs.append(f"{w} higher tier applies to GCSE only")
        if fmt == "mcq":
            o = opts.get(qid, [])
            if len(o) < 2 or sum(o) != 1: errs.append(f"{w} needs at least two options and exactly one correct")
            if rubric.get((qid, None)) != 1: errs.append(f"{w} rubric must total 1 mark")
        elif fmt == "written":
            if marks == 0 and ty != ["speak"]: errs.append(f"{w} only speaking questions can be marked as a whole (0 marks)")
            if rubric.get((qid, None), -1) != marks: errs.append(f"{w} rubric totals {rubric.get((qid, None), 0)}, exam marks are {marks}")
        else:
            ps = parts.get(qid, [])
            if not ps: errs.append(f"{w} no parts")
            if sum(p[1] for p in ps) != marks: errs.append(f"{w} exam marks must equal the sum of its parts")
            for pid, mk, sub, ssid in ps:
                if ssid != sid: errs.append(f"{w} a part tests a subtopic of another subject")
                if sub not in tags.get(qid, set()): errs.append(f"{w} a part's subtopic is not tagged on the question")
                if rubric.get((qid, pid)) != mk: errs.append(f"{w} part rubric does not add up to the part's marks")
            if (qid, None) in rubric: errs.append(f"{w} multi-part rubric criteria belong to parts")
    return errs

# ---------- commands ----------

def run_scripts():
    for s in ("build_questions.py", "verify.py"):
        r = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", s)], capture_output=True, text=True, encoding="utf-8",
                           env={**os.environ, "PYTHONIOENCODING": "utf-8"})
        tail = (r.stdout + r.stderr).strip().splitlines()[-3:]
        if r.returncode: raise SystemExit(f"{s} failed:\n" + "\n".join(tail))
        print(s, "->", tail[-1])

def main(cmd):
    if cmd == "build":
        con = build(); print("built", DBFILE, con.execute("SELECT count(*) FROM question").fetchone()[0], "questions")
    elif cmd == "sync":
        con = open_db(); n, gone = sync(con, read_html()[2])
        errs = validate(con); print(f"synced {n} questions ({gone} removed); {len(errs)} problems")
        for e in errs[:30]: print("  " + e)
        if not same(export_data(con), read_html()[2]): raise SystemExit("round trip differs: the database cannot reproduce DATA")
        dump(con); print("wrote", DATA_SQL)
    elif cmd == "validate":
        errs = validate(open_db()); print("\n".join(errs[:100]) or "no problems"); print(len(errs), "problems")
        if errs: raise SystemExit(1)
    elif cmd == "check":
        ok = same(export_data(open_db()), read_html()[2]); print("round trip", "OK" if ok else "DIFFERS")
        if not ok: raise SystemExit(1)
    elif cmd == "export":
        con = open_db(); errs = validate(con)
        if errs: raise SystemExit(f"{len(errs)} problems; fix them first (python scripts/db.py validate)")
        write_html(export_data(con)); dump(con); print("wrote DATA into index.html and", DATA_SQL); run_scripts()
    elif cmd == "dump":
        dump(open_db()); print("wrote", DATA_SQL)
    else:
        raise SystemExit(__doc__ or "usage: python scripts/db.py build|sync|validate|check|export|dump")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "")
